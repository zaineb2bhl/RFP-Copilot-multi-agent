"""DOCX export: response sections, compliance table and cited sources (python-docx)."""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

from docx import Document
from docx.document import Document as DocxDocument
from docx.shared import Pt
from docx.text.paragraph import Paragraph

from rfp_copilot.models import (
    ComplianceRow,
    ComplianceStatus,
    Requirement,
    ResponseGroup,
    RetrievedPassage,
    ReviewResult,
    extract_citations,
)

_INLINE_RE = re.compile(r"(\*\*[^*]+\*\*|\*[^*]+\*)")
_STATUS_LABELS: dict[ComplianceStatus, str] = {
    "addressed": "Addressed",
    "partially_addressed": "Partially addressed",
    "not_addressed": "Not addressed",
}


_citations = extract_citations


def build_compliance_rows(
    requirements: list[Requirement],
    groups: list[ResponseGroup],
    drafts: dict[str, str],
    reviews: dict[str, ReviewResult],
) -> list[ComplianceRow]:
    """Compute one compliance row per requirement, deterministically.

    `where_addressed` uses the section numbering of the exported document (1.N).
    Status: `not_addressed` if the section has no draft or never mentions the requirement id;
    `partially_addressed` if it is mentioned but the reviewer listed it as uncovered;
    otherwise `addressed`. Sources are the citations in the paragraphs mentioning the id
    (or in the whole section if none of them cite anything).
    """
    group_of = {
        req_id: (i, g) for i, g in enumerate(groups, start=1) for req_id in g.requirement_ids
    }
    rows: list[ComplianceRow] = []
    for req in requirements:
        number, group = group_of.get(req.id, (None, None))
        draft = drafts.get(group.id, "") if group else ""
        review = reviews.get(group.id) if group else None
        if not draft or req.id not in draft:
            status: ComplianceStatus = "not_addressed"
        elif review and req.id in review.uncovered_requirements:
            status = "partially_addressed"
        else:
            status = "addressed"
        sources: list[str] = []
        if status != "not_addressed":
            paragraphs = [p for p in draft.split("\n") if req.id in p]
            sources = _citations("\n".join(paragraphs)) or _citations(draft)
        rows.append(
            ComplianceRow(
                requirement_id=req.id,
                requirement_text=req.text,
                type=req.type,
                status=status,
                where_addressed=f"1.{number} {group.title}" if group and draft else "-",
                sources=sources,
            )
        )
    return rows


def _add_inline(paragraph: Paragraph, text: str) -> None:
    """Add text to a paragraph, rendering **bold** and *italic* markdown spans."""
    for part in _INLINE_RE.split(text):
        if not part:
            continue
        if part.startswith("**") and part.endswith("**"):
            paragraph.add_run(part[2:-2]).bold = True
        elif part.startswith("*") and part.endswith("*") and len(part) > 2:
            paragraph.add_run(part[1:-1]).italic = True
        else:
            paragraph.add_run(part)


def add_markdown(doc: DocxDocument, markdown: str, *, base_heading_level: int = 2) -> None:
    """Render a small markdown subset (headings, bullet/numbered lists, bold, italic)."""
    for raw in markdown.splitlines():
        line = raw.strip()
        if not line:
            continue
        if heading := re.match(r"^(#{1,6})\s+(.*)$", line):
            level = min(9, base_heading_level + len(heading.group(1)) - 1)
            doc.add_heading(heading.group(2).strip("* "), level=level)
        elif bullet := re.match(r"^[-*+]\s+(.*)$", line):
            _add_inline(doc.add_paragraph(style="List Bullet"), bullet.group(1))
        elif numbered := re.match(r"^\d+[.)]\s+(.*)$", line):
            _add_inline(doc.add_paragraph(style="List Number"), numbered.group(1))
        else:
            _add_inline(doc.add_paragraph(), line)


def export_docx(
    path: Path | str,
    *,
    rfp_title: str,
    groups: list[ResponseGroup],
    drafts: dict[str, str],
    compliance: list[ComplianceRow],
    passages: dict[str, RetrievedPassage],
) -> Path:
    """Write the response document to `path` and return it."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = Document()
    doc.styles["Normal"].font.size = Pt(10.5)

    doc.add_heading(f"Technical Response: {rfp_title}", level=0)
    note = doc.add_paragraph()
    note.add_run(
        f"Draft generated by RFP Copilot on {date.today().isoformat()}. Citations in square "
        "brackets refer to the knowledge-base sources listed at the end. This draft must be "
        "reviewed by the bid team before submission."
    ).italic = True

    doc.add_heading("1. Response", level=1)
    for number, group in enumerate(groups, start=1):
        doc.add_heading(f"1.{number} {group.title}", level=2)
        meta = doc.add_paragraph()
        meta.add_run(f"Requirements addressed: {', '.join(group.requirement_ids)}").italic = True
        add_markdown(
            doc, drafts.get(group.id, "_No draft for this section._"), base_heading_level=3
        )

    doc.add_heading("2. Compliance matrix", level=1)
    table = doc.add_table(rows=1, cols=4)
    table.style = "Table Grid"
    for cell, label in zip(
        table.rows[0].cells, ("Requirement", "Status", "Where addressed", "Sources"), strict=True
    ):
        cell.text = ""
        cell.paragraphs[0].add_run(label).bold = True
    for row in compliance:
        cells = table.add_row().cells
        cells[0].text = f"{row.requirement_id} ({row.type}): {row.requirement_text}"
        cells[1].text = _STATUS_LABELS[row.status]
        cells[2].text = row.where_addressed
        cells[3].text = ", ".join(row.sources) or "-"

    doc.add_heading("3. Sources", level=1)
    cited = list(dict.fromkeys(c for d in drafts.values() for c in _citations(d)))
    if not cited:
        doc.add_paragraph("No sources cited.")
    for chunk_id in cited:
        passage = passages.get(chunk_id)
        label = (
            f"{passage.source}, {passage.title}" if passage else "unknown source (not retrieved)"
        )
        p = doc.add_paragraph(style="List Bullet")
        p.add_run(f"[{chunk_id}]").bold = True
        p.add_run(f" {label}")

    doc.save(path)
    return path
